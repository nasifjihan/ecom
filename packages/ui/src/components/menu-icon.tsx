/** A menu item's icon: one of MENU_ICONS, or a small image from its link. */
import {
  Backpack,
  Baby,
  Bike,
  BookOpen,
  Briefcase,
  Camera,
  Coffee,
  Crown,
  Dumbbell,
  Flame,
  Flower,
  Footprints,
  Gem,
  Gift,
  Glasses,
  Headphones,
  Heart,
  Home,
  Lamp,
  Laptop,
  Moon,
  Package,
  Palette,
  Percent,
  Scissors,
  Shirt,
  ShoppingBag,
  Smartphone,
  Snowflake,
  Sofa,
  Sparkles,
  Star,
  Store,
  Sun,
  Tag,
  Truck,
  Umbrella,
  Utensils,
  Watch,
  Zap,
  type LucideIcon,
} from "lucide-react";
import { isMenuIcon, type MenuIcon as MenuIconName } from "@ecom/shared-types";
import { cn } from "@ecom/utils";

export const MENU_ICON_COMPONENTS: Record<MenuIconName, LucideIcon> = {
  shirt: Shirt,
  footprints: Footprints,
  watch: Watch,
  gem: Gem,
  glasses: Glasses,
  baby: Baby,
  gift: Gift,
  "shopping-bag": ShoppingBag,
  backpack: Backpack,
  briefcase: Briefcase,
  crown: Crown,
  sparkles: Sparkles,
  flower: Flower,
  heart: Heart,
  star: Star,
  tag: Tag,
  percent: Percent,
  zap: Zap,
  flame: Flame,
  sun: Sun,
  moon: Moon,
  snowflake: Snowflake,
  umbrella: Umbrella,
  scissors: Scissors,
  palette: Palette,
  home: Home,
  sofa: Sofa,
  lamp: Lamp,
  utensils: Utensils,
  coffee: Coffee,
  smartphone: Smartphone,
  laptop: Laptop,
  headphones: Headphones,
  camera: Camera,
  dumbbell: Dumbbell,
  bike: Bike,
  "book-open": BookOpen,
  package: Package,
  truck: Truck,
  store: Store,
};

export function MenuIcon({ icon, className }: { icon?: string | null; className?: string }) {
  if (!icon) return null;
  if (isMenuIcon(icon)) {
    const Icon = MENU_ICON_COMPONENTS[icon];
    return <Icon className={cn("h-4 w-4 shrink-0", className)} aria-hidden="true" />;
  }
  if (/^(\/(?!\/)|https?:\/\/)/i.test(icon)) return <img src={icon} alt="" className={cn("h-4 w-4 shrink-0 rounded-sm object-cover", className)} />;
  return null;
}
